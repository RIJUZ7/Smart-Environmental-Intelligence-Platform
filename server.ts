import express, { Request, Response } from 'express';
import path from 'path';
import { fileURLToPath } from 'url';
import dotenv from 'dotenv';
import { GoogleGenAI } from '@google/genai';

dotenv.config();

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const app = express();
const PORT = process.env.PORT ? parseInt(process.env.PORT, 10) : 3000;

app.use(express.json({ limit: '20mb' }));

// Initialize Google GenAI client if GEMINI_API_KEY is available
const geminiApiKey = process.env.GEMINI_API_KEY;
let aiClient: GoogleGenAI | null = null;

if (geminiApiKey) {
  aiClient = new GoogleGenAI({
    apiKey: geminiApiKey,
    httpOptions: {
      headers: {
        'User-Agent': 'aistudio-build',
      },
    },
  });
}

// Health & System Status Endpoint
app.get('/api/status', (_req: Request, res: Response) => {
  res.json({
    status: 'online',
    timestamp: new Date().toISOString(),
    hasGeminiKey: !!geminiApiKey,
    nodeEnv: process.env.NODE_ENV || 'development',
    version: '1.0.0-field-observatory'
  });
});

// AI Environmental Field Report Generation Endpoint
app.post('/api/reports/generate', async (req: Request, res: Response) => {
  try {
    const {
      reportType = 'executive_field_summary',
      datasetMeta,
      summaryStats,
      anomalies = [],
      dateRange,
      selectedStation,
      customPrompt
    } = req.body;

    if (!aiClient) {
      return res.status(503).json({
        error: 'GEMINI_API_KEY is not configured on the server.',
        message: 'The server-side Gemini client requires an attached GEMINI_API_KEY secret. Configure it via the AI Studio Secrets panel.'
      });
    }

    // Build strict scientific prompt grounded ONLY in supplied facts
    const systemInstruction = `You are a senior environmental scientist and field data analyst writing an objective, evidence-based Field Observatory Report for ECO-SENSE.

CRITICAL SCIENTIFIC RULES:
1. ONLY utilize the provided statistical metrics, counts, dates, units, and anomalies supplied in the context.
2. NEVER invent, hallucinate, or extrapolate unmeasured chemicals, sensor values, or fictitious external sources.
3. NEVER make speculative medical diagnoses, definitive regulatory penalties, or unsupported causal assertions. Distinguish correlation from causation.
4. Clearly identify data provenance (e.g. state explicitly if this is the "Demonstration Dataset" vs "Imported Field Telemetry").
5. If data is sparse, missing, or exhibits telemetry gaps, explicitly document this in the "Limitations and Uncertainty" section.
6. Adopt an authoritative, calm, precise scientific tone ("Field Observatory" voice).`;

    const promptPayload = `Please compose a comprehensive ${reportType.replace(/_/g, ' ').toUpperCase()} report for the following observatory parameters:

[DATASET INFORMATION]
- Title: ${datasetMeta?.title || 'Unknown Dataset'}
- Provenance: ${datasetMeta?.provenance === 'demo' ? 'DEMO DATA — NOT LIVE MEASUREMENTS' : 'User Imported Telemetry'}
- Observation Date Range: ${dateRange?.start || 'N/A'} to ${dateRange?.end || 'N/A'}
- Selected Station: ${selectedStation || 'All Observatory Stations'}
- Overall Data Quality Score: ${datasetMeta?.dataQualityScore ?? 'N/A'}/100
- Quality Breakdown: Completeness: ${datasetMeta?.qualityBreakdown?.completeness ?? 'N/A'}%, Validity: ${datasetMeta?.qualityBreakdown?.validity ?? 'N/A'}%, Consistency: ${datasetMeta?.qualityBreakdown?.consistency ?? 'N/A'}%, Timeliness: ${datasetMeta?.qualityBreakdown?.timeliness ?? 'N/A'}%

[CALCULATED SUMMARY STATISTICS]
${JSON.stringify(summaryStats || {}, null, 2)}

[DETECTED SCIENTIFIC ANOMALIES (${anomalies.length} total)]
${JSON.stringify(
  anomalies.slice(0, 15).map((a: Record<string, unknown>) => ({
    metric: a.metricLabel || a.metric,
    station: a.stationName,
    timestamp: a.timestamp,
    observedValue: a.observedValue,
    expectedRange: a.expectedRange,
    method: a.detectionMethod,
    severity: a.severity,
    explanation: a.explanation
  })),
  null,
  2
)}

${customPrompt ? `[ANALYST INQUIRY / SPECIFIC FOCUS]\n${customPrompt}\n` : ''}

STRUCTURE YOUR SCIENTIFIC REPORT AS FOLLOWS:
# 1. OBSERVATORY EXECUTIVE SUMMARY
# 2. METEOROLOGICAL & CHEMICAL PATTERNS
# 3. DETECTED ANOMALY EVALUATION & MECHANISMS
# 4. DATA QUALITY, COMPLETENESS & LIMITATIONS
# 5. RECOMMENDED SCIENTIFIC FOLLOW-UPS (Non-speculative actions)

Include a prominent attribution note at the conclusion: "Generated by ECO-SENSE Observatory AI Engine (${new Date().toISOString()}). All interpretations require human scientific peer review."`;

    const response = await aiClient.models.generateContent({
      model: 'gemini-3.8-flash',
      contents: promptPayload,
      config: {
        systemInstruction,
        temperature: 0.2, // Low temperature for high factual reproducibility
      }
    });

    const reportMarkdown = response.text || 'No text output returned from model.';

    return res.json({
      reportMarkdown,
      modelUsed: 'gemini-3.8-flash',
      generatedAt: new Date().toISOString(),
      reportType,
      station: selectedStation || 'All'
    });
  } catch (err: unknown) {
    const errorMsg = err instanceof Error ? err.message : 'Unknown generation error';
    console.error('Error generating environmental report:', err);
    return res.status(500).json({
      error: 'Failed to generate environmental report',
      details: errorMsg
    });
  }
});

// In dev, mount Vite middleware; in prod, serve build
async function startServer() {
  if (process.env.NODE_ENV === 'production') {
    app.use(express.static(path.resolve(__dirname, 'dist')));
    app.get('*', (_req: Request, res: Response) => {
      res.sendFile(path.resolve(__dirname, 'dist', 'index.html'));
    });
  } else {
    const { createServer: createViteServer } = await import('vite');
    const vite = await createViteServer({
      server: { middlewareMode: true },
      appType: 'spa',
    });
    app.use(vite.middlewares);
  }

  app.listen(PORT, '0.0.0.0', () => {
    console.log(`[ECO-SENSE Field Observatory] Server running at http://0.0.0.0:${PORT}`);
    console.log(`[ECO-SENSE] Gemini API Key present: ${!!geminiApiKey}`);
  });
}

startServer();
